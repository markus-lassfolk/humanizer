#!/usr/bin/env node
/**
 * build-en-locale-prescriptive.mjs — TSV → src/locales/generated/en-prescriptive.js
 *
 * Usage: node locales/en-en/scripts/build-en-locale-prescriptive.mjs [--check]
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(__dirname, '..', '..', '..');
const EN_REF = path.join(REPO_ROOT, 'locales/en-en/references');
const outFile = path.join(REPO_ROOT, 'src/locales/generated/en-prescriptive.js');

const TSV_FILES = [
  path.join(EN_REF, 'plain-english.tsv'),
  path.join(EN_REF, 'plain-english-bulk.tsv'),
  path.join(EN_REF, 'microsoft-style-guide.tsv'),
  path.join(EN_REF, 'google-developer-style.tsv'),
  path.join(EN_REF, 'mozilla-style.tsv'),
  path.join(EN_REF, 'weasel-words.tsv'),
  path.join(EN_REF, 'cliches.tsv'),
  path.join(EN_REF, 'redundancy.tsv'),
  path.join(EN_REF, 'hedging.tsv'),
  path.join(EN_REF, 'inclusive-language.tsv'),
  path.join(EN_REF, 'corporate-jargon.tsv'),
];

function escapeRegex(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function escapeForRegexLiteralBody(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/\//g, '\\/');
}

function parseTsvFile(filePath) {
  const text = fs.readFileSync(filePath, 'utf8');
  const rows = [];
  for (const line of text.split(/\n/)) {
    const t = line.trimEnd();
    if (!t.trim() || t.trimStart().startsWith('#')) continue;
    const cols = t.split('\t');
    while (cols.length < 7) cols.push('');
    rows.push({
      avoid: (cols[0] || '').trim(),
      prefer: (cols[1] || '').trim(),
      kind: (cols[2] || '').trim(),
      tier: (cols[3] || '').trim(),
      fix_hint: (cols[4] || '').trim(),
      pattern: (cols[5] || '').trim(),
      notes: (cols[6] || '').trim(),
    });
  }
  return rows;
}

function tierNumber(row) {
  if (row.kind === 'tier1_phrase') return 1;
  const n = parseInt(row.tier, 10);
  if (n === 1 || n === 2 || n === 3) return n;
  return 2;
}

function labelForAutofix(row) {
  if (!row.prefer) return `Removed "${row.avoid}"`;
  return `"${row.avoid}" → "${row.prefer}"`;
}

function buildAutofixPatternSource(row) {
  if (row.pattern) return row.pattern;
  return `\\b${escapeForRegexLiteralBody(escapeRegex(row.avoid))}\\b`;
}

function buildPhrasePatternSource(row) {
  if (row.pattern) return row.pattern;
  return `\\b${escapeForRegexLiteralBody(escapeRegex(row.avoid))}\\b`;
}

function main() {
  const check = process.argv.includes('--check');

  const allRows = [];
  for (const f of TSV_FILES) {
    if (!fs.existsSync(f)) {
      console.error(`Missing TSV: ${path.relative(REPO_ROOT, f)}`);
      process.exit(1);
    }
    allRows.push(...parseTsvFile(f));
  }

  const seenAutofix = new Set();
  const seenPhrase = new Set();
  const autofixes = [];
  const phrases = [];

  for (const row of allRows) {
    if (!row.avoid) {
      console.error('Row missing avoid:', row);
      process.exit(1);
    }
    const kind = row.kind;
    if (!kind || kind === 'skip') continue;

    if (kind === 'autofix') {
      const key = `autofix:${row.avoid.toLowerCase()}`;
      if (seenAutofix.has(key)) {
        console.error(`Duplicate autofix avoid: ${row.avoid}`);
        process.exit(1);
      }
      seenAutofix.add(key);
      const patSrc = buildAutofixPatternSource(row);
      const replacement = row.prefer.replace(/\\n/g, '\n');
      autofixes.push({
        patternSrc: patSrc,
        replacement,
        label: labelForAutofix(row),
      });
    } else if (kind === 'phrase_flag' || kind === 'tier1_phrase' || kind === 'template') {
      const patSrc = buildPhrasePatternSource(row);
      const pkey = patSrc.toLowerCase();
      if (seenPhrase.has(pkey)) continue;
      seenPhrase.add(pkey);
      const tier = tierNumber(row);
      const fix = row.fix_hint || row.prefer || '(rephrase)';
      phrases.push({ patternSrc: patSrc, tier, fix });
    } else {
      console.error(`Unknown kind "${kind}" for avoid "${row.avoid}"`);
      process.exit(1);
    }
  }

  const afLines = autofixes.map(
    (a) =>
      `  { pattern: /${a.patternSrc}/gi, replacement: ${JSON.stringify(a.replacement)}, label: ${JSON.stringify(a.label)} },`,
  );
  const phLines = phrases.map(
    (p) => `  { pattern: /${p.patternSrc}/gi, tier: ${p.tier}, fix: ${JSON.stringify(p.fix)} },`,
  );

  const header = `/**
 * Generated by locales/en-en/scripts/build-en-locale-prescriptive.mjs — do not edit by hand.
 * Source: locales/en-en/references/*.tsv
 */
/* eslint-disable */
`;

  const body = `${header}
module.exports.AUTOFIXES_EN_PRESCRIPTIVE = [
${afLines.join('\n')}
];

module.exports.AI_PHRASES_EN_PRESCRIPTIVE = [
${phLines.join('\n')}
];
`;

  if (check) {
    if (!fs.existsSync(outFile)) {
      console.error('Missing generated file; run: npm run locale:prescriptive-en');
      process.exit(1);
    }
    const existing = fs.readFileSync(outFile, 'utf8');
    if (existing !== body) {
      console.error('en-prescriptive.js is stale; run: npm run locale:prescriptive-en');
      process.exit(1);
    }
    console.log('en-prescriptive.js is up to date');
    return;
  }

  const outDir = path.dirname(outFile);
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

  fs.writeFileSync(outFile, body, 'utf8');
  console.log(
    `Wrote ${path.relative(REPO_ROOT, outFile)} (${autofixes.length} autofixes, ${phrases.length} phrases)`,
  );
}

main();
